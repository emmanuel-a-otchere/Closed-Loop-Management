"""CLAM topology-as-script toolkit (Slice 7 PR3).

Reads a topology spec (JSON) describing decision models,
activities, workflows, goals, closed loops, and closed-loop
links, and emits a runnable Python script that recreates the
topology by POSTing to a live CLAM API in dependency order
(decision models -> activities -> workflows -> goals ->
closed loops -> links).

The emitted script is self-contained apart from ``httpx``
(already a project dependency) and the target base URL.
It is intended for environment reproduction, DR drills, and
CI seeding.

Spec shape::

    {
      "decisionModels": [{"id": "...", "name": "...", "kind": "OODA"}],
      "activities":     [{"id": "...", "name": "...", "kind": "sense"}],
      "workflows":      [{"id": "...", "name": "..."}],
      "goals":          [{"id": "...", "name": "...", "targetValue": 0.99}],
      "closedLoops":    [{"id": "...", "name": "...",
                          "decisionModelId": "..."}],
      "closedLoopLinks":[{"id": "...", "sourceLoopId": "...",
                          "targetLoopId": "...", "linkType": "hierarchical"}]
    }

Any section may be omitted; the script simply skips it.

CLI usage::

    clam-topology-script --spec topology.json \\
        --base http://localhost:8000 \\
        --out reproduce_topology.py
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

__all__ = ["render_script", "load_spec", "main"]


# Endpoints in dependency order. (spec key, API path)
_SECTIONS: list[tuple[str, str]] = [
    ("decisionModels", "/api/v1/decisionModels"),
    ("activities", "/api/v1/activities"),
    ("workflows", "/api/v1/workflows"),
    ("goals", "/api/v1/goals"),
    ("closedLoops", "/api/v1/closedLoops"),
    ("closedLoopLinks", "/api/v1/closedLoopLinks"),
]


def load_spec(path: Path) -> dict[str, list[dict[str, Any]]]:
    """Load a topology spec; returns a dict of section -> list of items."""
    data = json.loads(path.read_text())
    if not isinstance(data, dict):
        raise ValueError("topology spec must be a JSON object")
    out: dict[str, list[dict[str, Any]]] = {}
    for key, _ in _SECTIONS:
        value = data.get(key, [])
        if not isinstance(value, list):
            raise ValueError(f"section {key!r} must be a list")
        out[key] = value
    return out


def render_script(
    spec: dict[str, list[dict[str, Any]]],
    *,
    base_url: str = "http://localhost:8000",
) -> str:
    """Render the runnable reproduction script."""
    lines: list[str] = [
        '"""Reproduce a CLAM topology against a live service.',
        "",
        "Generated by ``clam-topology-script``. Do not edit by hand;",
        "regenerate from the topology spec instead.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "import sys",
        "",
        "import httpx",
        "",
        "",
        f"BASE = {base_url!r}",
        "",
        "",
        "def main() -> int:",
        '    with httpx.Client(base_url=BASE, timeout=30.0) as client:',
    ]
    emitted = False
    for section, api_path in _SECTIONS:
        items = spec.get(section, [])
        if not items:
            continue
        emitted = True
        lines.append(f"        # --- {section} ({len(items)}) ---")
        for item in items:
            label = item.get("id") or item.get("name") or "<unnamed>"
            body = json.dumps(item, sort_keys=True)
            lines.append(f"        r = client.post({api_path!r}, json={body})")
            lines.append(
                f"        assert r.status_code in (200, 201, 409), "
                f"f'{section}:{label}: {{r.status_code}} {{r.text}}'"
            )
            lines.append(
                f"        print(f'{section}:{label}: {{r.status_code}}')"
            )
        lines.append("")
    if not emitted:
        lines.append("        pass  # topology spec has no entities")
        lines.append("")
    lines.append("    return 0")
    lines.append("")
    lines.append("")
    lines.append('if __name__ == "__main__":')
    lines.append("    sys.exit(main())")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", type=Path, required=True)
    parser.add_argument(
        "--base",
        default="http://localhost:8000",
        help="Target CLAM base URL (baked into the emitted script)",
    )
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    if not args.spec.exists():
        print(f"spec not found: {args.spec}", file=sys.stderr)
        return 2

    spec = load_spec(args.spec)
    script = render_script(spec, base_url=args.base)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(script)
    total = sum(len(v) for v in spec.values())
    print(f"Wrote topology script ({total} entities) to {args.out}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
